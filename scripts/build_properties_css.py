"""Build the properties-only Mobirise CSS; requires tinycss2 (build time only)."""

import argparse
import re
from html.parser import HTMLParser
from pathlib import Path

import tinycss2

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/mobirise/css/mbr-additional.css'
OUTPUT = ROOT / 'assets/mobirise/css/mbr-properties.css'


class PageClasses(HTMLParser):
    def __init__(self):
        super().__init__()
        self.classes = set()

    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if name == 'class' and value:
                self.classes.update(value.split())


def relevant_selector(prelude, classes):
    branches = [[]]
    for token in prelude:
        if token.type == 'literal' and token.value == ',':
            branches.append([])
        else:
            branches[-1].append(token)
    for branch in branches:
        selector = tinycss2.serialize(branch).strip()
        anchor = re.match(r'^\.(cid-[a-zA-Z0-9_-]+)(?=[\s.:#\[>+~]|$)', selector)
        # Only discard selectors anchored to absent generated sections. Keep all
        # global, dynamic (hover/open/mobile), and unfamiliar selectors intact.
        if not anchor or anchor.group(1) in classes:
            return True
    return False


def subset(rules, classes):
    result = []
    for rule in rules:
        if rule.type == 'error':
            raise ValueError(f'Invalid CSS: {rule.message}')
        if rule.type in ('comment', 'whitespace'):
            continue
        if rule.type == 'qualified-rule':
            if relevant_selector(rule.prelude, classes):
                result.append(rule.serialize())
        elif rule.type == 'at-rule' and rule.lower_at_keyword in ('media', 'supports'):
            children = subset(tinycss2.parse_rule_list(rule.content), classes)
            if children:
                result.append('@' + rule.at_keyword + tinycss2.serialize(rule.prelude)
                              + '{\n' + children + '\n}')
        else:
            result.append(rule.serialize())
    # Mobirise repeats the same menu rules for many pages. Keep the last exact
    # copy so specificity and source-order precedence remain unchanged.
    seen = set()
    unique = []
    for text in reversed(result):
        if text not in seen:
            unique.append(text)
            seen.add(text)
    return '\n'.join(reversed(unique))


def build():
    page = PageClasses()
    page.feed((ROOT / 'properties.html').read_text(encoding='utf-8'))
    source = SOURCE.read_text(encoding='utf-8')
    css = subset(tinycss2.parse_stylesheet(source), page.classes)
    return ('/* Generated by scripts/build_properties_css.py. Do not edit directly.\n'
            '   Regenerate after changing section classes or mbr-additional.css. */\n'
            + css + '\n').encode('utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != generated:
            raise SystemExit('mbr-properties.css is stale; run scripts/build_properties_css.py')
    else:
        OUTPUT.write_bytes(generated)
    print(f'Properties CSS: {len(generated):,} bytes (source: {SOURCE.stat().st_size:,})')
